"""Grade 6 standalone optional-worksheet content (Project Plan item 8).

Generates data/grade6_worksheets.ts: 10 worksheets per subject x 4 subjects
(Language, Math, Science, SocialStudies) = 40 worksheets, 15 multiple-choice
questions each (Grade 6 is multiple-choice only per the pipeline rules in
gen_worksheets.py). These are supplementary practice worksheets, a separate
pipeline from the day-based data/grade6.ts curriculum -- overlap with topics
already covered across the 187 days is expected and fine.

Each subject's 10 worksheets are organized around 10 distinct practice
themes spanning the grade, roughly foundational to more advanced. All
answers are authored at index 0 (correct answer first) for readability,
then _rebalance() shuffles each subject's correct-answer slot across A/B/C/D
so there is no bias toward one position.

No embedded straight double-quotes or apostrophes anywhere in title/q/
option text -- apostrophes are dropped entirely (e.g. "Earths" not
"Earth's", "Canadas" not "Canada's"), matching the rest of the Grade 6
content. gen_worksheets.mc()/worksheet() assert this, so any stray
quote/apostrophe fails loudly at generation time.

Usage: python3 gen_grade6_worksheets.py
"""
import sys, os, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_worksheets import mc, worksheet, write_worksheets


def _rebalance(subject_worksheets, seed):
    """subject_worksheets: list of (title, questions) where questions is a
    list of (q, opts, a) raw tuples (all authored with a=0). Returns a new
    list of the same shape with each questions correct-answer index
    reshuffled across 0-3 so the subjects 150 questions are evenly split
    A/B/C/D."""
    rng = random.Random(seed)
    all_q = [q for _, qs in subject_worksheets for q in qs]
    n = len(all_q)
    targets = [i % 4 for i in range(n)]
    rng.shuffle(targets)
    idx = 0
    out = []
    for title, qs in subject_worksheets:
        new_qs = []
        for (q, opts, a) in qs:
            correct = opts[a]
            wrong = [o for j, o in enumerate(opts) if j != a]
            rng.shuffle(wrong)
            target = targets[idx]
            idx += 1
            new_opts = [None, None, None, None]
            new_opts[target] = correct
            wi = 0
            for slot in range(4):
                if new_opts[slot] is None:
                    new_opts[slot] = wrong[wi]
                    wi += 1
            new_qs.append((q, new_opts, target))
        out.append((title, new_qs))
    return out


def _build_subject(subject, subject_worksheets, seed):
    if len(subject_worksheets) != 10:
        raise AssertionError(f'{subject}: expected 10 worksheets, got {len(subject_worksheets)}')
    for _t, _qs in subject_worksheets:
        if len(_qs) != 15:
            raise AssertionError(f'{subject}/{_t!r}: expected 15 questions, got {len(_qs)}')
    balanced = _rebalance(subject_worksheets, seed)
    out = []
    for i, (title, qs) in enumerate(balanced, start=1):
        questions = [mc(q, opts, a) for (q, opts, a) in qs]
        out.append(worksheet(subject, i, title, questions))
    return out


