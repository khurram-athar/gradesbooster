#!/usr/bin/env python3
"""Grade 11 standalone optional-worksheet content (Project Plan item 8).
This is a NEW, separate content pipeline from data/grade11.ts (the 187-day
lesson sequence) -- these are supplementary multiple-choice practice
worksheets, not new lessons, and are allowed to reinforce topics already
covered across the 187 days.

Builds exactly 10 worksheets per subject x 4 subjects (English, Functions,
Biology, Chemistry -- Grade 11's real subject set) = 40 worksheets, each
with exactly 15 mc() questions (Grade 11 is multiple-choice only per the
project plan), using the shared helpers in gen_worksheets.py.

Each of the 10 worksheets per subject is organized around a distinct
practice theme/strand spanning the grade's curriculum, roughly progressing
from foundational to more advanced topics within that subject.

Authoring approach: each question is authored as a (question_text,
correct_answer_text, [wrong1, wrong2, wrong3]) tuple via qd(), always with
the correct answer conceptually "first" for ease of writing. build_mc_list()
then rebalances the correct-answer position across indices 0-3 within each
worksheet (using a per-worksheet seed) before handing questions to mc(),
so there is no bias toward any one option letter.

No embedded straight double-quotes or apostrophes anywhere in title/
question/option text -- contractions and possessives are dropped or
reworded throughout (e.g. "does not" not "doesnt", "atom relative ability"
not "atom's relative ability"), matching the hard assert()s in
gen_worksheets.py's mc()/worksheet() helpers.
"""
import random
import sys
sys.path.insert(0, '.')
from gen_worksheets import mc, worksheet, write_worksheets


def qd(text, correct, wrongs):
    """One authored question: text, the correct answer string, and exactly
    3 wrong answer strings. Position is assigned later by build_mc_list()."""
    assert len(wrongs) == 3, f'expected exactly 3 wrong answers, got {len(wrongs)}: {text!r}'
    return (text, correct, wrongs)


def build_mc_list(items, seed):
    """Turns a list of qd() tuples into a list of mc() questions, spreading
    the correct-answer index roughly evenly across 0-3 within this list."""
    assert len(items) == 15, f'expected exactly 15 items, got {len(items)}'
    rng = random.Random(seed)
    n = len(items)
    targets = [i % 4 for i in range(n)]
    rng.shuffle(targets)
    out = []
    for (text, correct, wrongs), target in zip(items, targets):
        opts = [None, None, None, None]
        opts[target] = correct
        remaining = list(wrongs)
        rng.shuffle(remaining)
        wi = 0
        for slot in range(4):
            if opts[slot] is None:
                opts[slot] = remaining[wi]
                wi += 1
        out.append(mc(text, opts, target))
    return out


def ws(subject, number, title, items, seed):
    return worksheet(subject, number, title, build_mc_list(items, seed))


